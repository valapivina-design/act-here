def main():
    # Fix broken section in ihtiyal-online if present
    for p in PAGES:
        if p["slug"] != "ihtiyal-online":
            continue
        fixed = []
        for sec in p["sections"]:
            kicker, h2, blocks = sec
            new_blocks = []
            for b in blocks:
                if b[0] == "h3" and b[1] == []:
                    continue
                if b[0] == "h3" and isinstance(b[1], list):
                    continue
                new_blocks.append(b)
            fixed.append((kicker, h2, new_blocks))
        p["sections"] = fixed

    os.makedirs(AR, exist_ok=True)
    out = {p["slug"] + ".html": render(p) for p in PAGES}
    out["index.html"] = render_index()
    problems = []
    for name, html in out.items():
        bad = sorted(set(c for c in html if c in CHARS_BANNED))
        if bad:
            problems.append(f"{name}: banned characters {bad}")
        hit = WORDS_BANNED.search(html)
        if hit:
            problems.append(f"{name}: banned wording '{hit.group(0)}'")
        for m in re.finditer(r'<script type="application/ld\+json">(.*?)</script>', html, re.S):
            json.loads(m.group(1))
    for p in PAGES:
        if len(p["description"]) > 175:
            problems.append(f"{p['slug']}: description {len(p['description'])} chars")
    if problems:
        sys.exit("BUILD FAILED\n" + "\n".join(problems))
    for name, html in out.items():
        with open(os.path.join(AR, name), "w", encoding="utf-8") as f:
            f.write(html)
    print(f"wrote {len(out)} files to ar/ (copy rules passed, JSON-LD valid)")

if __name__ == "__main__":
    main()
